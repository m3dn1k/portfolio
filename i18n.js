var LANGS = ["ru", "en", "zh"];

function readLang() {
  var fromUrl;
  try {
    fromUrl = new URLSearchParams(location.search).get("lang");
  } catch (e) {}
  var fromStore;
  try {
    fromStore = localStorage.getItem("lang");
  } catch (e) {}
  var raw = fromUrl || fromStore || "ru";
  return LANGS.indexOf(raw) >= 0 ? raw : "ru";
}

function applyLang(lang) {
  if (LANGS.indexOf(lang) < 0) lang = "ru";
  var pack = I18N[lang];
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  document.documentElement.dataset.lang = lang;
  document.title = pack.title;
  var meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", pack.desc);
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-alt");
    if (pack[key] != null) el.setAttribute("alt", pack[key]);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    if (pack[key] != null) el.setAttribute("placeholder", pack[key]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-aria");
    if (pack[key] != null) el.setAttribute("aria-label", pack[key]);
  });
  var switcher = document.getElementById("lang-switch");
  if (switcher) {
    switcher.setAttribute("aria-label", pack.langLabel);
    switcher.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });
  }
  try {
    localStorage.setItem("lang", lang);
  } catch (e) {}
}

applyLang(readLang());

document.getElementById("lang-switch").addEventListener("click", function (e) {
  var btn = e.target.closest("[data-lang]");
  if (!btn) return;
  applyLang(btn.getAttribute("data-lang"));
});
